  function normalizeRoute(kmlCoords) {
    return kmlCoords.map(([lon, lat]) => ({
      lat,
      lon,
    }));
  }
  const normalizedRoute = normalizeRoute(kmlRoute);

  function haversine(lat1, lon1, lat2, lon2) {
    const R = 6371;
    const dLat = ((lat2 - lat1) * Math.PI) / 180;
    const dLon = ((lon2 - lon1) * Math.PI) / 180;

    const a =
      Math.sin(dLat / 2) ** 2 +
      Math.cos((lat1 * Math.PI) / 180) *
        Math.cos((lat2 * Math.PI) / 180) *
        Math.sin(dLon / 2) ** 2;

    return 2 * R * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  }

  function addCumulativeDistance(route) {
    let total = 0;

    return route.map((point, i) => {
      if (i > 0) {
        total += haversine(
          route[i - 1].lat,
          route[i - 1].lon,
          point.lat,
          point.lon,
        );
      }
      return { ...point, km: total };
    });
  }

  const busRouteWithKm = addCumulativeDistance(normalizedRoute);
  const startPoint = snapToRoute(startLat, startLon, busRouteWithKm);
  const currentPoint = snapToRoute(currentLat, currentLon, busRouteWithKm);

  return Math.abs(currentPoint.km - startPoint.km);
